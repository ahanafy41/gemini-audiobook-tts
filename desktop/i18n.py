def normalize_lang(lang: str) -> str:
    """Returns 'ar' if Arabic is requested, otherwise defaults to 'en'."""
    if isinstance(lang, str) and lang.strip().lower().startswith("ar"):
        return "ar"
    return "en"


def tr(key: str, lang: str = "en", **kwargs: Any) -> str:
    """
    Safely retrieves a localized string by key for the specified language ('en' or 'ar')
    and formats any keyword placeholders.
    """
    code = normalize_lang(lang)
    catalog = TRANSLATIONS.get(code, TRANSLATIONS["en"])
    template = catalog.get(key) or TRANSLATIONS["en"].get(key) or key
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template


